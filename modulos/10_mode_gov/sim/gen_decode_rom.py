# generates r8064_decode_rom.v: ROM A (256x12) and ambiguity ROM (256x8) as combinational logic (case), from rom_ed_a.mem / amb_idx.mem.
# REV53c: also page 32 of ROM_B (rom_ed_b.mem entries 8192..8447) as r8064_rom_b32, so the BSRAM ROM_B is exactly 8192 deep.
# Reason: as "reg []" + $readmemh yosys absorbs the address register (b2) into the read port and takes the D->b2 path into the ROM.
import sys
def mk(name,fn,w,lo=0,hi=256):
    v=[int(l,16) for l in open(fn) if l.strip() and not l.startswith('//')][lo:hi]
    s=f"(* keep_hierarchy *) module {name}(input wire [7:0] a, output reg [{w-1}:0] d);\n    always @* case (a)\n"
    for i,x in enumerate(v): s+=f"        8'd{i}: d = {w}'h{x:0{(w+3)//4}x};\n"
    return s+f"        default: d = {w}'h0;\n    endcase\nendmodule\n"
open('../rtl/r8064_decode_rom.v','w').write("// GENERATED by sim/gen_decode_rom.py - do not edit\n"+mk('r8064_rom_a','rom_ed_a.mem',12)+mk('r8064_rom_amb','amb_idx.mem',8)
    +mk('r8064_rom_b32','rom_ed_b.mem',10,8192,8448))   # REV53c: page 32 of ROM_B as logic (frees one BSRAM)

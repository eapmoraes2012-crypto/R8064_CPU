#!/usr/bin/env python3
# make_bench_pkg.py - builds the Gowin EDA package of the TIMING BENCH (r8064_bench_top, bare Tang Nano 20K, results on the USB serial):
#   <out>/src/r8064_bench_all.v : the RTL of the cartridge (list and macros of ../pnr/ys_cart.ys) with r8064_bench_top in place of the slot
#                                 top, in ONE file, with absolute .mem/.hex paths
#   <out>/src/*.mem             : ROM images (uop, decoder, governor), copied from ../pnr
#   <out>/src/monitor_l0..7.hex : the bench firmware (../bench/gen_bench.py), loaded into the boot buffer in place of the monitor
#   <out>/src/tangnano20k_bench.cst, r8064_bench.sdc, <out>/gowin_build.tcl, <out>/rodar_gowin.bat, <out>/LEIA-ME_bench.txt
# Usage: python3 make_bench_pkg.py [--bm] [--nofpu] <out_dir> [<absolute path of out_dir/src as Gowin will see it, e.g. C:/Users/me/Documents/R8064_bench/src/>]
#   --bm: the boot image is the board benchmarks (../bench/bm/board/build_board.py: Dhrystone, Sieve, soft float; needs SDCC, see there)
#         instead of the timing-bench firmware. REV53: 27 MHz (CPT 8), FPU included, reference timings ../bench/ref_rev53.json.
import os, re, shutil, sys, subprocess

# ROMs whose width is not a multiple of 4 bits: Gowin EDA reports "Entry size .. does not match memory width" (EX2526) for their
# hex files and does not load them as iverilog does (the core then runs a wrong microcode). For Gowin they go as $readmemb files
# with exactly the memory width.
BIN_ROMS = [('uop.mem', 'uop_bin.mem', 107, '$readmemh(UOP_FILE, uopm)', '$readmemb(UOP_FILE, uopm)'),
            ('rom_ed_b.mem', 'rom_ed_b_bin.mem', 10, '$readmemh(ROM_B_FILE, rom_b, 0, 8191)', '$readmemb(ROM_B_FILE, rom_b)')]
BIN_LINES = {'rom_ed_b.mem': 8192}   # REV53c: Gowin gets only the 32 BSRAM pages (page 32 is logic, r8064_rom_b32)
def bin_roms(text, src_dir, out_dir, P):
    for hexf, binf, w, old, new in BIN_ROMS:
        assert old in text, old
        text = text.replace(old, new).replace('"%s%s"' % (P, hexf), '"%s%s"' % (P, binf))
        lines = [l.strip() for l in open(os.path.join(src_dir, hexf)) if l.strip() and not l.startswith('//')][:BIN_LINES.get(hexf)]
        with open(os.path.join(out_dir, binf), 'w', newline='\r\n') as f:
            for l in lines:
                v = int(l, 16); assert v < (1 << w), (hexf, l)
                f.write(format(v, '0%db' % w) + '\n')
    return text
HERE = os.path.dirname(os.path.abspath(__file__)); PNR = os.path.join(HERE, '..', 'pnr'); BENCH = os.path.join(HERE, '..', 'bench')
BM = '--bm' in sys.argv; NOFPU = '--nofpu' in sys.argv; args = [a for a in sys.argv[1:] if not a.startswith('--')]
out = os.path.abspath(args[0]); src = os.path.join(out, 'src'); os.makedirs(src, exist_ok=True)
P = args[1] if len(args) > 1 else src.replace('\\', '/') + '/'
if not P.endswith('/'): P += '/'
if BM:
    subprocess.run([sys.executable, os.path.join(BENCH, 'bm', 'board', 'build_board.py'), os.path.join(out, 'bm_build')], check=True)
    for g in range(8): shutil.copy(os.path.join(out, 'bm_build', 'monitor_l%d.hex' % g), src)
    shutil.copy(os.path.join(out, 'bm_build', 'board.bin'), os.path.join(src, 'bench.bin'))
else:
    subprocess.run([sys.executable, os.path.join(BENCH, 'gen_bench.py'), os.path.join(BENCH, 'ref_rev53.json'), src], check=True)
first = open(os.path.join(PNR, 'ys_cart.ys'), encoding='utf-8').read().split('\n')[0]
defs = re.findall(r'-D(\w+)', first)
if NOFPU: defs += ['R8064_NOFPU', 'R8064_NO_FPU']      # diagnosis: the same bench without the FPU
files = [f for f in first.split() if f.endswith('.v') and not re.search(r'r8064_cart_top|r8064_slot_if|r8064_slot_dec', f)] + ['../rtl/r8064_bench_top.v']
MEMS = ['gov_rom.mem', 'uop.mem', 'mainctrl.mem', 'rom_ed_a.mem', 'rom_ed_b.mem', 'amb_idx.mem', 'ctrl_b.mem']
o = ['// r8064_bench_all.v - GENERATED by modulos/13_soc/gowin/make_bench_pkg.py: RTL of the timing bench (r8064_bench_top) in one file',
     '// for Gowin EDA, with the build macros of ys_cart.ys and absolute paths for the .mem/.hex files. Regenerate from the sources; do not edit.']
o += ['`define ' + d for d in defs] + ['']
for f in files:
    s = open(os.path.join(PNR, f), encoding='utf-8').read().replace('\r\n', '\n')
    for n in MEMS: s = s.replace('"%s"' % n, '"%s%s"' % (P, n))
    s = s.replace('INIT_PFX = "monitor_l"', 'INIT_PFX = "%smonitor_l"' % P)
    o += ['// ===================== %s =====================' % os.path.normpath(f).replace(os.sep, '/'), s]
open(os.path.join(src, 'r8064_bench_all.v'), 'w', newline='\r\n').write(bin_roms('\n'.join(o), PNR, src, P))
for n in MEMS: shutil.copy(os.path.join(PNR, n), src)
for n in ('bench.bin', ): os.remove(os.path.join(src, n))
for n in ('tangnano20k_bench.cst', 'r8064_bench.sdc'): shutil.copy(os.path.join(BENCH, n), src)
tcl = open(os.path.join(HERE, 'gowin_build.tcl'), encoding='utf-8').read()
tcl = tcl.replace('r8064_cart.fs', 'r8064_bench.fs').replace('r8064_cart_all.v', 'r8064_bench_all.v').replace('tangnano20k_cart.cst', 'tangnano20k_bench.cst').replace('r8064_cart.sdc', 'r8064_bench.sdc')
tcl = tcl.replace('r8064_cart_top', 'r8064_bench_top').replace('-name r8064_cart', '-name r8064_bench').replace('-output_base_name r8064_cart', '-output_base_name r8064_bench')
tcl = tcl.replace('-global_freq 28.64', '-global_freq 27').replace('R8064 cartridge', 'R8064 timing bench')
open(os.path.join(out, 'gowin_build.tcl'), 'w', newline='\r\n').write(tcl)
bat = open(os.path.join(HERE, 'rodar_gowin.bat'), encoding='utf-8').read().replace('R8064 cartridge', 'R8064 timing bench')
open(os.path.join(out, 'rodar_gowin.bat'), 'w', newline='\r\n').write(bat)
shutil.copy(os.path.join(BENCH, 'LEIA-ME_bench.txt'), out)
print('bench package in', out, '| macros:', ' '.join(defs), '| files:', len(files), '| ROM path:', P)

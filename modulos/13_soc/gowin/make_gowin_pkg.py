#!/usr/bin/env python3
# make_gowin_pkg.py - builds the Gowin EDA package of the cartridge (r8064_cart_top) from the sources:
#   <out>/src/r8064_cart_all.v  : all RTL listed in ../pnr/ys_cart.ys in ONE file, with the build macros of ys_cart.ys (-D...) as `define
#                                 and the .mem/.hex paths made absolute (Gowin resolves $readmemh paths unreliably)
#   <out>/src/*.mem, *.hex      : ROM images (uop, decoder, governor, monitor), copied from ../pnr
#   <out>/src/tangnano20k_cart.cst, r8064_cart.sdc, <out>/gowin_build.tcl, <out>/rodar_gowin.bat
# Usage: python3 make_gowin_pkg.py [--reduced] <out_dir> [<absolute path of out_dir/src as Gowin will see it, e.g. C:/Users/me/Documents/R8064_gowin/src/>]
#   Default (REV49b): the macros of ys_cart.ys = FPU and 4 DMA channels, 32-bit addresses (R8064_AW32), no MLTSQ/MLTUQ/DIVSQ/DIVUQ (R8064_NO_MD64).
#   --full: no macros (64-bit addresses and 64-bit MUL/DIV too).  --reduced: also R8064_DMA2 (2 DMA channels).
#   --reduced-nofpu: the REV47/REV48 cartridge (R8064_NOFPU R8064_DMA2 R8064_AW32 R8064_NO_MD64).
import os, re, shutil, sys

# ROMs whose width is not a multiple of 4 bits: Gowin EDA reports "Entry size .. does not match memory width" (EX2526) for their
# hex files and does not load them as iverilog does (the core then runs a wrong microcode). For Gowin they go as $readmemb files
# with exactly the memory width.
BIN_ROMS = [('uop.mem', 'uop_bin.mem', 107, '$readmemh(UOP_FILE, uopm)', '$readmemb(UOP_FILE, uopm)'),
            ('rom_ed_b.mem', 'rom_ed_b_bin.mem', 10, '$readmemh(ROM_B_FILE, rom_b)', '$readmemb(ROM_B_FILE, rom_b)')]
def bin_roms(text, src_dir, out_dir, P):
    for hexf, binf, w, old, new in BIN_ROMS:
        assert old in text, old
        text = text.replace(old, new).replace('"%s%s"' % (P, hexf), '"%s%s"' % (P, binf))
        lines = [l.strip() for l in open(os.path.join(src_dir, hexf)) if l.strip() and not l.startswith('//')]
        with open(os.path.join(out_dir, binf), 'w', newline='\r\n') as f:
            for l in lines:
                v = int(l, 16); assert v < (1 << w), (hexf, l)
                f.write(format(v, '0%db' % w) + '\n')
    return text
HERE = os.path.dirname(os.path.abspath(__file__)); PNR = os.path.join(HERE, '..', 'pnr')
args = [a for a in sys.argv[1:] if not a.startswith('--')]; opts = [a for a in sys.argv[1:] if a.startswith('--')]
out = os.path.abspath(args[0]); src = os.path.join(out, 'src'); os.makedirs(src, exist_ok=True)
P = args[1] if len(args) > 1 else src.replace('\\', '/') + '/'
if not P.endswith('/'): P += '/'
first = open(os.path.join(PNR, 'ys_cart.ys'), encoding='utf-8').read().split('\n')[0]
defs = re.findall(r'-D(\w+)', first)
if '--full' in opts: defs = []
if '--reduced' in opts: defs += ['R8064_DMA2', 'R8064_AW32', 'R8064_NO_MD64']
if '--reduced-nofpu' in opts: defs += ['R8064_NOFPU', 'R8064_DMA2', 'R8064_AW32', 'R8064_NO_MD64']
defs = list(dict.fromkeys(defs))
files = [f for f in first.split() if f.endswith('.v')]
MEMS = ['gov_rom.mem', 'uop.mem', 'mainctrl.mem', 'rom_ed_a.mem', 'rom_ed_b.mem', 'amb_idx.mem', 'ctrl_b.mem']
o = ['// r8064_cart_all.v - GENERATED by modulos/13_soc/gowin/make_gowin_pkg.py: all RTL of the cartridge top (r8064_cart_top) in one file',
     '// for Gowin EDA, with the build macros of ys_cart.ys and absolute paths for the .mem/.hex files. Regenerate from the sources; do not edit.']
o += ['`define ' + d for d in defs] + ['']
for f in files:
    s = open(os.path.join(PNR, f), encoding='utf-8').read().replace('\r\n', '\n')
    for n in MEMS: s = s.replace('"%s"' % n, '"%s%s"' % (P, n))
    s = s.replace('INIT_PFX = "monitor_l"', 'INIT_PFX = "%smonitor_l"' % P)
    o += ['// ===================== %s =====================' % os.path.normpath(f).replace(os.sep, '/'), s]
open(os.path.join(src, 'r8064_cart_all.v'), 'w', newline='\r\n').write(bin_roms('\n'.join(o), PNR, src, P))
for n in MEMS + ['monitor_l%d.hex' % i for i in range(8)] + ['tangnano20k_cart.cst']: shutil.copy(os.path.join(PNR, n), src)
shutil.copy(os.path.join(HERE, 'r8064_cart.sdc'), src)
for n in ('gowin_build.tcl', 'rodar_gowin.bat'): shutil.copy(os.path.join(HERE, n), out)
print('package in', out, '| macros:', ' '.join(defs), '| files:', len(files), '| ROM path:', P)
